/**
 * Writes src/sim/heightData.ts: every ant, termite and creature model's height, zoned belly clearance, half-width and
 * feet (combat v2.2, CHANGE_PLAN §20; tools/heightLib.ts measures them), and prints the table in millimetres with the
 * pairs that can pass under each other (docs/combat/underpass.md).
 *
 *   npx vite-node tools/height-data.ts            # write the file and print the table
 *   npx vite-node tools/height-data.ts -- table   # print only
 */
import { writeFileSync } from 'node:fs';
import { allHeights } from './heightLib';
import { CASTES } from '../src/sim/species';
import { CREATURES } from '../src/sim/creatures/kinds';
import { BALANCE } from '../src/sim/balance';

const only = process.argv.includes('table');
const H = allHeights();
const fmt = (o: unknown) => JSON.stringify(o);
if (!only) {
  const body = (m: Record<string, unknown>) => Object.entries(m).map(([k, v]) => `    ${/^[a-z]\w*$/i.test(k) ? k : `'${k}'`}: ${fmt(v)},`).join('\n');
  const src = `// Generated by tools/height-data.ts from the unit models; edit the tool, not this file.

/** A unit's height data (fractions of its length; x forward from its middle): see tools/heightLib.ts. */
export interface HeightDef {
  /** highest point of the body standing */
  h: number;
  /** zone boundaries along the body: rear | middle, middle | front */
  zx: [number, number];
  /** clearance under the rear, middle and front zones */
  c: [number, number, number];
  /** half-width of the body */
  hw: number;
  /** the feet on the ground: x, z pairs */
  feet: number[];
}

export const HEIGHTS: { ant: Record<string, HeightDef>; creature: Record<string, HeightDef> } = {
  ant: {
${body(H.ant)}
  },
  creature: {
${body(H.creature)}
  },
};
`;
  writeFileSync('src/sim/heightData.ts', src);
  console.log('wrote src/sim/heightData.ts');
}
// the table, in mm, per caste
const U = (BALANCE as { underpass?: { margin: number } }).underpass;
const margin = U?.margin ?? 0.1;
const rows: Array<{ id: string; L: number; h: number; c: number[] }> = [];
for (const [id, c] of Object.entries(CASTES)) {
  const d = c.morph ? H.ant[c.morph] : undefined;
  if (!d) continue;
  rows.push({ id, L: c.length, h: d.h * c.length, c: d.c.map((v) => v * c.length) });
}
for (const [id, k] of Object.entries(CREATURES)) {
  const d = H.creature[id];
  if (d) rows.push({ id: 'cr:' + id, L: k.length, h: d.h * k.length, c: d.c.map((v) => v * k.length) });
}
console.log('unit                    length  height  clearance rear / middle / front (mm)');
for (const r of rows) console.log(`${r.id.padEnd(22)} ${r.L.toFixed(1).padStart(6)}  ${r.h.toFixed(2).padStart(6)}  ${r.c.map((v) => v.toFixed(2)).join(' / ')}`);
// who fits under whom (same species, and every ant under creatures), by zone
const fits = (a: (typeof rows)[0], b: (typeof rows)[0]) => ['rear', 'middle', 'front'].filter((_, z) => a.h * (1 + margin) <= b.c[z]);
console.log('\npasses under (same species):');
for (const b of rows) {
  if (b.id.startsWith('cr:')) continue;
  const sp = (CASTES[b.id] as { species?: string }).species;
  const under = rows.filter((a) => !a.id.startsWith('cr:') && a !== b && (CASTES[a.id] as { species?: string }).species === sp).map((a) => [a.id, fits(a, b)] as const).filter(([, z]) => z.length);
  if (under.length) console.log(`  under ${b.id}: ${under.map(([id, z]) => `${id} (${z.join(', ')})`).join('; ')}`);
}
