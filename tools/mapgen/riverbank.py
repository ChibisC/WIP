"""Riverbank (docs/maps/design.md §9): 1,800 x 1,400 mm. A winding stream from the west edge to the east
edge, off-centre: a high bank to the north with six sites, a low muddy bank to the south with four; two
stepping-stone crossings and a fallen-leaf raft; driftwood and stones on the banks; reed beds; washed-up
food along both banks; the stream rises over the south bank's mud margin after rain (off by default).

  python3 tools/mapgen/riverbank.py src/maps/riverbank.ts
"""
import math, sys
sys.path.insert(0, __file__.rsplit('/', 1)[0])
from tsemit import emit, P

W, D = 1800.0, 1400.0


def yc(x):
    """the stream's centre line"""
    return 640 + 105 * math.sin(2 * math.pi * x / 1150 + 0.5) + 38 * math.sin(2 * math.pi * x / 470 + 1.4)


stream = [P(x, yc(x)) for x in range(-20, 1841, 40)]
SW = 72  # stream width

def crossing(x, half=62):
    # perpendicular to the local direction of the stream
    dx, dy = 20, yc(x + 10) - yc(x - 10)
    l = math.hypot(dx, dy); nx, ny = -dy / l, dx / l
    return [P(x + nx * half, yc(x) + ny * half), P(x - nx * half, yc(x) - ny * half)]


def blob(cx, cy, r, seed, n=11, elong=1.0, rotd=0.0):
    pts = []
    for k in range(n):
        a = k * 2 * math.pi / n
        rr = r * (1 + 0.16 * math.sin(3 * a + seed) + 0.09 * math.sin(5 * a + seed * 1.7) + 0.05 * math.sin(7 * a + seed * 0.3))
        x, y = math.cos(a) * rr * elong, math.sin(a) * rr / elong
        ca, sa = math.cos(math.radians(rotd)), math.sin(math.radians(rotd))
        pts.append(P(cx + x * ca - y * sa, cy + x * sa + y * ca))
    return pts


# sites: six on the high north bank, four on the low south bank
north = [P(170, 250), P(470, 330), P(780, 220), P(1060, 330), P(1360, 230), P(1650, 320)]
south = [P(330, 1120), P(720, 1200), P(1110, 1110), P(1490, 1190)]
sites_at = north + south


def ent(s):
    # entrances face the stream
    d = 1 if s[1] < yc(s[0]) else -1
    return P(s[0], s[1] + d * 22)


walls = []
# driftwood: logs washed up along both banks (paths), lying roughly along the stream
for (x0, x1, off, w) in [(240, 420, -105, 34), (980, 1170, -110, 30), (560, 760, 120, 38), (1300, 1500, 118, 32)]:
    walls.append({'kind': 'log', 'shape': {'path': [P(x0, yc(x0) + off), P(x1, yc(x1) + off)], 'width': w}, 'height': w})
# stones on the banks
for i, (x, off, r) in enumerate([(120, -150, 26), (640, -160, 22), (910, 150, 28), (1240, -170, 24), (1700, 160, 26), (40, 170, 20)]):
    walls.append({'kind': 'stone' if r < 25 else 'rock', 'shape': {'poly': blob(x, yc(x) + off, r, 0.7 + i * 1.3, 11, 1.25, i * 23)}, 'height': round(r * 0.8)})

walkways = [
    {'kind': 'stone', 'shape': {'path': crossing(430), 'width': 34}},
    {'kind': 'leaf', 'shape': {'path': crossing(905), 'width': 36}},
    {'kind': 'stone', 'shape': {'path': crossing(1380), 'width': 34}},
]

# the south bank's mud margin: a band along the stream that floods after rain
margin = [P(x, yc(x) + SW / 2 + 70) for x in range(-20, 1841, 60)] + [P(x, yc(x) + SW / 2 - 4) for x in range(1840, -21, -60)]

d = dict(
    const='RIVERBANK', id='riverbank', name='Riverbank',
    blurb='A winding stream between a high bank and a low muddy one. Stepping stones and a leaf raft cross it; food washes up along the banks; reed beds and driftwood.',
    biome='riverbank', style='riverbank', width=int(W), depth=int(D), relief=(5, 260),
    doc='Riverbank (docs/maps/design.md §9): a winding stream from the west edge to the east, off-centre;\nsix sites on the high north bank, four on the low south bank; two stepping-stone crossings and a\nfallen-leaf raft; driftwood and stones; washed-up food along both banks; the stream rises over the\nsouth bank\'s mud margin after rain (floods are off by default).\n\nA DRAFT, generated by tools/mapgen/riverbank.py: validated, not yet in PLAYABLE_MAPS (art to do).',
    brushes=[
        {'shape': {'poly': [P(-20, -20), P(1820, -20), P(1820, 420), P(-20, 420)]}, 'amount': 4, 'falloff': 160, 'note': 'the high north bank'},
        {'shape': {'poly': margin}, 'amount': -1.5, 'falloff': 60, 'note': 'the low mud margin on the south bank'},
    ],
    water=[{'kind': 'stream', 'shape': {'path': stream, 'width': SW}, 'level': -2, 'depth': 9, 'bed': 24}],
    walkways=walkways,
    walls=walls,
    sites=[{'at': s, 'entrances': [ent(s)]} for s in sites_at],
    siteSets={2: [[1, 7], [4, 8], [0, 9], [5, 6]], 3: [[1, 4, 7], [0, 5, 8]], 4: [[0, 5, 6, 9], [1, 4, 7, 8]], 10: [list(range(10))]},
    zones=[
        *[{'kind': 'food', 'shape': {'circle': P(x, yc(x) + off), 'r': 55}, 'weight': 2, 'name': 'washed up'} for x, off in [(200, -95), (700, 175), (1150, -95), (1620, 175)]],
        *[{'kind': 'food', 'shape': {'circle': c, 'r': 60}} for c in [P(620, 110), P(1210, 110), P(520, 1310), P(1300, 1310)]],
        {'kind': 'aphid', 'shape': {'circle': P(900, 150), 'r': 45}, 'name': 'bankside willowherb'},
        {'kind': 'aphid', 'shape': {'circle': P(910, 1220), 'r': 45}, 'name': 'bankside willowherb'},
        {'kind': 'plant', 'shape': {'circle': P(330, 120), 'r': 45}},
        {'kind': 'plant', 'shape': {'circle': P(1500, 110), 'r': 45}},
        {'kind': 'plant', 'shape': {'circle': P(110, 1300), 'r': 45}},
        {'kind': 'plant', 'shape': {'circle': P(1700, 1300), 'r': 45}},
        {'kind': 'lair', 'shape': {'circle': P(30, 40), 'r': 30}, 'name': 'north burrow'},
        {'kind': 'lair', 'shape': {'circle': P(1770, 1360), 'r': 30}, 'name': 'south burrow'},
        {'kind': 'creature', 'shape': {'poly': [P(0, 0), P(1800, 0), P(1800, 80), P(0, 80)]}, 'note': 'wild creatures come from the far edges of both banks'},
        {'kind': 'creature', 'shape': {'poly': [P(0, 1320), P(1800, 1320), P(1800, 1400), P(0, 1400)]}},
    ],
    floods=[{'shape': {'poly': margin}, 'level': -1.0, 'first': [480, 720], 'every': [600, 900], 'hold': [45, 90], 'note': 'the stream rises over the south bank\'s mud margin'}],
)

if __name__ == '__main__':
    out = sys.argv[1] if len(sys.argv) > 1 else None
