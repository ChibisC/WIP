/**
 * Generates src/sim/termiteRoyalData.ts from the termite model kit (v2.1 royals), so the simulation's
 * royal geometry cannot drift from the models: body lengths (front of the head to the abdomen tip),
 * how far the abdomen reaches behind the model origin (ground under the thorax centre = the sim
 * position), the egg-lay point (Bone.EGG_LAY pivot) and the half-width of the queen's abdomen; and the
 * Sickle-Jaw soldier's grab socket (where the crossed mandible tips hold a victim) and front.
 *
 * Used by tools/termite-royal-data.ts (writes the file) and tests/combat.ts (checks it is current).
 */
import { buildTermiteGeometry } from '../src/render/termite/build';
import { Bone, Mat, RigCol, TermiteRig } from '../src/render/termite/rig';
import type { CasteId } from '../src/render/termite/castes';

const r2 = (x: number) => Math.round(x * 100) / 100;

export function royalData() {
  const out: Record<string, { length: number; front: number; back: number; halfWidth: number; abdFront: number; abdHalfWidth: number; eggLay: [number, number, number] }> = {};
  for (const caste of ['queen', 'king', 'rhy_queen', 'rhy_king'] as CasteId[]) {
    const g = buildTermiteGeometry(caste, 1);
    const rig = g.userData.rig as TermiteRig;
    const p = rig.pivots;
    const e = Bone.EGG_LAY * 3;
    const back = -rig.bounds.min[0];
    // widest point of the abdomen itself (its mesh, not the hairs)
    const pos = g.getAttribute('position');
    const rv = g.getAttribute('aRig');
    let abdHW = 0;
    for (let i = 0; i < pos.count; i++) if (rv.getX(i) === Bone.ABDOMEN && rv.getZ(i) !== Mat.SETA) abdHW = Math.max(abdHW, Math.abs(pos.getZ(i)));
    out[caste] = {
      length: r2(rig.bodyLength),
      front: r2(rig.bodyLength - back),
      back: r2(back),
      halfWidth: r2(Math.max(-rig.bounds.min[2], rig.bounds.max[2])),
      abdFront: r2(rig.texRow[RigCol.ABD_INFO * 4]),
      abdHalfWidth: r2(abdHW),
      eggLay: [r2(p[e]), r2(p[e + 1]), r2(p[e + 2])],
    };
    g.dispose();
  }
  return out;
}

export function royalDataSource(): string {
  const d = royalData();
  return `// GENERATED by tools/termite-royal-data.ts from the termite model kit (src/render/termite). Do not edit.
// Model millimetres; x forward from the model origin (ground under the thorax centre = the sim position).
// length: front of the head to the abdomen tip; back: the abdomen tip behind the origin; halfWidth: widest
// point (legs included); abdFront / abdHalfWidth: where the abdomen starts (x) and its half-width;
// eggLay: the queen's Bone.EGG_LAY pivot, where a laid egg appears. Keys: the kit's caste ids (sim morph 'termite_' + id).
export const TERMITE_ROYALS = {
${Object.entries(d)
  .map(([k, v]) => `  ${k}: { length: ${v.length}, front: ${v.front}, back: ${v.back}, halfWidth: ${v.halfWidth}, abdFront: ${v.abdFront}, abdHalfWidth: ${v.abdHalfWidth}, eggLay: [${v.eggLay.join(', ')}] },`)
  .join('\n')}
} as const;
`;
}

